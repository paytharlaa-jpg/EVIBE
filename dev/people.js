// Dev check: load a person GLB, list its clips/tracks, play a clip.
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/examples/jsm/loaders/DRACOLoader.js';
import { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
const q = new URLSearchParams(location.search);
const url = q.get('m') || '/models/people/guest-c.glb';
const r = new THREE.WebGLRenderer({ antialias: true });
r.setSize(innerWidth, innerHeight);
document.body.appendChild(r.domElement);
const scene = new THREE.Scene();
scene.add(new THREE.HemisphereLight('#fff', '#334', 2.5));
scene.environment = new THREE.PMREMGenerator(r).fromScene(new RoomEnvironment()).texture;
scene.background = new THREE.Color('#556');
const cam = new THREE.PerspectiveCamera(35, innerWidth / innerHeight, 0.1, 50);
cam.position.set(+(q.get('cx') || 2.6), 1.2, +(q.get('cz') || 2.6));
cam.lookAt(0, 0.8, 0);
const grid = new THREE.GridHelper(4, 8);
scene.add(grid);
const l = new GLTFLoader();
const d = new DRACOLoader();
d.setDecoderPath('/draco/');
l.setDRACOLoader(d);
const g = await l.loadAsync(url);
scene.add(g.scene);
const info = { clips: g.animations.map((c) => [c.name, c.duration.toFixed(2), c.tracks.length, c.tracks.slice(0, 3).map((t) => t.name)]) };
const names = [];
g.scene.traverse((o) => names.push(o.type + ':' + o.name));
info.nodes = names.slice(0, 12);
const mixer = new THREE.AnimationMixer(g.scene);
const clip = g.animations.find((c) => c.name === (q.get('c') || 'sit')) || g.animations[0];
const a = mixer.clipAction(clip);
a.play();
mixer.update(+(q.get('t') || 1));
const missing = clip.tracks.filter((t) => !g.scene.getObjectByName(t.name.split('.')[0])).map((t) => t.name);
info.missing = missing.slice(0, 5);
info.missingCount = missing.length;
g.scene.updateMatrixWorld(true);
g.scene.traverse((o) => o.isSkinnedMesh && o.computeBoundingBox());
const box = new THREE.Box3().setFromObject(g.scene, true);
let mat = null;
g.scene.traverse((o) => { if (o.isMesh && !mat) mat = { metal: o.material.metalness, rough: o.material.roughness, map: !!o.material.map }; });
info.mat = mat;
info.box = [box.min.toArray().map((v) => +v.toFixed(2)), box.max.toArray().map((v) => +v.toFixed(2))];
window.__info = info;
r.render(scene, cam);
